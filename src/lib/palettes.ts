export function getPalette(id?: string): PaletteDefinition {
  return PALETTES.find((p) => p.id === id) || PALETTES[0];
}

export function applyThemePalette(paletteId?: string, isDark: boolean = false) {
  if (typeof document === "undefined") return;
  const palette = getPalette(paletteId);
  const vars = isDark ? palette.dark : palette.light;
  const root = document.documentElement;

  root.setAttribute("data-theme", palette.id);

  // Set explicit custom palette tokens
  for (const [key, value] of Object.entries(vars)) {
    root.style.setProperty(key, value);
  }

  // Set high-fidelity KPI Card Tokens matching NexaVerse reference design
  const kpi1 = vars["--kpi-1-bg"] || palette.colors[1];
  const kpi2 = vars["--kpi-2-bg"] || palette.colors[2];
  const kpi3 = vars["--kpi-3-bg"] || palette.colors[3];
  const kpi4 = vars["--kpi-4-bg"] || palette.colors[0];

  root.style.setProperty("--kpi-1-bg", kpi1);
  root.style.setProperty("--kpi-1-fg", getOptimalTextColor(kpi1));
  root.style.setProperty("--kpi-1-muted", getOptimalTextColor(kpi1, "muted"));

  root.style.setProperty("--kpi-2-bg", kpi2);
  root.style.setProperty("--kpi-2-fg", getOptimalTextColor(kpi2));
  root.style.setProperty("--kpi-2-muted", getOptimalTextColor(kpi2, "muted"));

  root.style.setProperty("--kpi-3-bg", kpi3);
  root.style.setProperty("--kpi-3-fg", getOptimalTextColor(kpi3));
  root.style.setProperty("--kpi-3-muted", getOptimalTextColor(kpi3, "muted"));

  root.style.setProperty("--kpi-4-bg", kpi4);
  root.style.setProperty("--kpi-4-fg", getOptimalTextColor(kpi4));
  root.style.setProperty("--kpi-4-muted", getOptimalTextColor(kpi4, "muted"));
}
