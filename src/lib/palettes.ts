/**
 * Calculates relative luminance for WCAG contrast checking.
 */
function getLuminance(hex: string): number {
  const cleanHex = hex.replace("#", "");
  const r = parseInt(cleanHex.substring(0, 2), 16) / 255;
  const g = parseInt(cleanHex.substring(2, 4), 16) / 255;
  const b = parseInt(cleanHex.substring(4, 6), 16) / 255;
  const a = [r, g, b].map((v) => (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
  return 0.2126 * a[0] + 0.7152 * a[1] + 0.0722 * a[2];
}

/**
 * Returns strictly White (#ffffff), Black (#000000), or Dark Grey (#1f2937 / #374151)
 * depending on the background luminance for optimal legibility.
 */
export function getOptimalTextColor(bgHex: string, type: "primary" | "muted" = "primary"): string {
  const lum = getLuminance(bgHex);
  // Dark background -> white or light text
  if (lum < 0.40) {
    return type === "muted" ? "#d1d5db" : "#ffffff";
  }
  // Light background -> black or dark grey text
  if (type === "muted") {
    return "#4b5563"; // Dark grey
  }
  return lum > 0.82 ? "#000000" : "#1f2937"; // Black or deep dark grey
}

